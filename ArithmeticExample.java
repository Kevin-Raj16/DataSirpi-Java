// Real-world example: Shopping bill calculation
public class ArithmeticExample {
    public static void main(String[] args) {

        int price = 500;
        int quantity = 3;

        int total = price * quantity; // multiplication
        int discount = 100;

        int finalAmount = total - discount; // subtraction

        System.out.println("Total: " + total);
        System.out.println("Final Amount: " + finalAmount);
    }
}
